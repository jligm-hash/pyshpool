// Package slurm generates native Slurm job-array scripts. It deliberately
// does not split task files: one array element maps to one input line.
package slurm

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/jligm-hash/pyshpool/v3/internal/core"
)

// Config describes an sbatch script.
type Config struct {
	TaskFile     string
	JobName      string
	Partition    string
	Account      string
	Nodes        int
	CPUsPerTask  int
	Array        string
	ArrayLimit   int
	TimeLimit    string
	Memory       string
	GRES         string
	NodeList     string
	Exclude      string
	MailType     string
	MailUser     string
	WorkDir      string
	Output       string
	Error        string
	ExtraOptions []string
}

// Generate returns a complete sbatch script and the absolute task-file path.
func Generate(cfg Config) (string, string, error) {
	if cfg.TaskFile == "" {
		return "", "", fmt.Errorf("task file is required")
	}
	absTask, err := filepath.Abs(cfg.TaskFile)
	if err != nil {
		return "", "", fmt.Errorf("resolve task file: %w", err)
	}
	lines, err := core.CountLines(absTask)
	if err != nil {
		return "", "", err
	}
	if lines == 0 {
		return "", "", fmt.Errorf("task file %q is empty", absTask)
	}

	workDir := cfg.WorkDir
	if workDir == "" {
		workDir, err = os.Getwd()
		if err != nil {
			return "", "", fmt.Errorf("resolve working directory: %w", err)
		}
	}
	if abs, err := filepath.Abs(workDir); err == nil {
		workDir = abs
	}

	array := cfg.Array
	if array == "" {
		array = fmt.Sprintf("1-%d", lines)
		if cfg.ArrayLimit > 0 {
			array += fmt.Sprintf("%%%d", cfg.ArrayLimit)
		}
	}

	nodes := cfg.Nodes
	if nodes <= 0 {
		nodes = 1
	}

	jobName := cfg.JobName
	if jobName == "" {
		jobName = "pysh"
	}
	output := cfg.Output
	if output == "" {
		output = "pysh-%A_%a.out"
	}
	errorPath := cfg.Error
	if errorPath == "" {
		errorPath = output
	}

	var b strings.Builder
	b.WriteString("#!/usr/bin/env bash\n")
	b.WriteString("# Generated by pysh. Submit with: sbatch <this-file>\n")
	fmt.Fprintf(&b, "#SBATCH --job-name=%s\n", jobName)
	fmt.Fprintf(&b, "#SBATCH --array=%s\n", array)
	fmt.Fprintf(&b, "#SBATCH --nodes=%d\n", nodes)
	if cfg.CPUsPerTask > 0 {
		fmt.Fprintf(&b, "#SBATCH --cpus-per-task=%d\n", cfg.CPUsPerTask)
	}
	if cfg.Partition != "" {
		fmt.Fprintf(&b, "#SBATCH --partition=%s\n", cfg.Partition)
	}
	// Only emit -A when an account was actually provided. An empty
	// "#SBATCH -A" is rejected by some Slurm configurations.
	if cfg.Account != "" {
		fmt.Fprintf(&b, "#SBATCH --account=%s\n", cfg.Account)
	}
	if cfg.TimeLimit != "" {
		fmt.Fprintf(&b, "#SBATCH --time=%s\n", cfg.TimeLimit)
	}
	if cfg.Memory != "" {
		fmt.Fprintf(&b, "#SBATCH --mem=%s\n", cfg.Memory)
	}
	if cfg.GRES != "" {
		fmt.Fprintf(&b, "#SBATCH --gres=%s\n", cfg.GRES)
	}
	if cfg.NodeList != "" {
		fmt.Fprintf(&b, "#SBATCH --nodelist=%s\n", cfg.NodeList)
	}
	if cfg.Exclude != "" {
		fmt.Fprintf(&b, "#SBATCH --exclude=%s\n", cfg.Exclude)
	}
	if cfg.MailType != "" {
		fmt.Fprintf(&b, "#SBATCH --mail-type=%s\n", cfg.MailType)
	}
	if cfg.MailUser != "" {
		fmt.Fprintf(&b, "#SBATCH --mail-user=%s\n", cfg.MailUser)
	}
	fmt.Fprintf(&b, "#SBATCH --chdir=%s\n", workDir)
	fmt.Fprintf(&b, "#SBATCH --output=%s\n", output)
	fmt.Fprintf(&b, "#SBATCH --error=%s\n", errorPath)
	for _, opt := range cfg.ExtraOptions {
		opt = strings.TrimSpace(opt)
		if opt == "" {
			continue
		}
		if !strings.HasPrefix(opt, "#SBATCH") {
			opt = "#SBATCH " + opt
		}
		b.WriteString(opt)
		b.WriteByte('\n')
	}

	fmt.Fprintf(&b, "\nset -euo pipefail\n\n")
	fmt.Fprintf(&b, "TASK_FILE=%s\n", shellQuote(absTask))
	fmt.Fprintf(&b, "WORK_DIR=%s\n", shellQuote(workDir))
	fmt.Fprintf(&b, "cd \"$WORK_DIR\"\n\n")
	b.WriteString("if [[ -z \"${SLURM_ARRAY_TASK_ID:-}\" ]]; then\n")
	b.WriteString("  echo \"pysh: SLURM_ARRAY_TASK_ID is not set; submit this file with sbatch\" >&2\n")
	b.WriteString("  exit 2\n")
	b.WriteString("fi\n\n")
	b.WriteString("cmd=\"$(sed -n \"${SLURM_ARRAY_TASK_ID}p\" \"$TASK_FILE\")\"\n")
	b.WriteString("if [[ -z \"${cmd//[[:space:]]/}\" ]]; then\n")
	b.WriteString("  echo \"pysh: array task ${SLURM_ARRAY_TASK_ID} has no command; skipping\"\n")
	b.WriteString("  exit 0\n")
	b.WriteString("fi\n\n")
	b.WriteString("echo \"pysh: array task ${SLURM_ARRAY_TASK_ID} on $(hostname) at $(date -Is)\"\n")
	b.WriteString("echo \"pysh: command: ${cmd}\"\n")
	b.WriteString("set +e\n")
	b.WriteString("bash -c \"$cmd\"\n")
	b.WriteString("status=$?\n")
	b.WriteString("set -e\n")
	b.WriteString("echo \"pysh: array task ${SLURM_ARRAY_TASK_ID} finished with status ${status} at $(date -Is)\"\n")
	b.WriteString("exit \"$status\"\n")

	return b.String(), absTask, nil
}

// ArrayRange returns a Slurm array expression for a task file, including an
// optional concurrency limit (for example "1-1000%50").
func ArrayRange(lines, limit int) string {
	if lines < 0 {
		lines = 0
	}
	s := "1-" + strconv.Itoa(lines)
	if limit > 0 {
		s += "%" + strconv.Itoa(limit)
	}
	return s
}

func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
